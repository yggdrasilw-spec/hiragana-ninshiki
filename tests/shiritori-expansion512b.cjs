const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),name='2026-10-14-expansion512b';
const json=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const review=json('data/dictionary-imports/'+name+'.review.json');
const source=json('data/dictionary-imports/'+name+'.source.json');
const summary=json('data/image-coverage/'+name+'/summary.json');
const plan=json('data/image-coverage/'+name+'/plan.json');
const manifest=json('assets/shiritori/manifest.json');
const text=fs.readFileSync(path.join(root,'whitelist.csv'),'utf8');
const lines=text.trimEnd().split(/\r?\n/),header=lines.shift().split(',');
const rows=lines.map(l=>Object.fromEntries(l.split(',').map((v,i)=>[header[i],v])));
assert.equal(review.length,512);assert.equal(source.rows.length,512);
assert.equal(summary.addedWords,512);assert.equal(new Set(review.map(r=>r.reading)).size,512);
assert.ok(rows.length>=summary.baselineRows+512);
const hash=s=>crypto.createHash('sha256').update(s).digest('hex');
const prefix=header.join(',')+'\n'+lines.slice(0,summary.baselineRows).join('\n')+'\n';
assert.equal(hash(prefix),summary.beforeSha256,'All columns and IDs of the original dictionary are preserved');
const oldReadings=new Set(rows.slice(0,summary.baselineRows).map(r=>r.reading));
const assets=new Map(manifest.assets.map(a=>[a.file,a]));
assert.equal(assets.size,manifest.assets.length,'No duplicate manifest filenames');
const norm=s=>s.replace(/[ァ-ヶ]/g,c=>String.fromCharCode(c.charCodeAt(0)-96));
const rules=fs.readFileSync(path.join(root,'blacklist.txt'),'utf8').split(/\r?\n/).map(l=>l.trim()).filter(l=>l&&!l.startsWith('#')).map(l=>{const m=l.match(/^(exact|contains)\s*[:=]\s*(.*)/i);return m?{mode:m[1].toLowerCase(),pattern:norm(m[2].trim())}:{mode:'contains',pattern:norm(l)};});
for(const item of review){
 const row=rows[item.id-1],p=plan.items.find(p=>p.id===item.id);
 assert.ok(!oldReadings.has(item.reading),'Independent new reading: '+item.reading);
 assert.match(item.reading,/^[ぁ-ゖー]{2,}$/);assert.ok(!item.reading.endsWith('ん'));
 assert.ok(!rules.some(r=>r.mode==='exact'?item.reading===r.pattern:item.reading.includes(r.pattern)));
 for(const key of ['reading','word','meaning'])assert.equal(row[key],item[key]);
 assert.equal(Number(row.level),item.level);assert.ok(item.lexicalSource&&item.meaningReason&&item.ageReason&&item.imageReason);
 assert.equal(item.imageStatus,'covered');assert.equal(row.image_mode,'asset');
 assert.equal(row.image_asset,'assets/shiritori/'+p.filename);
 const asset=assets.get(p.filename);assert.ok(asset,'Recorded image provenance');
 assert.ok(asset.aliases.some(a=>a.id===item.id&&a.reading===item.reading&&a.word===item.word&&a.meaning===item.meaning),'Every shared sense is recorded');
 const bytes=fs.readFileSync(path.join(root,row.image_asset));
 assert.equal(bytes.readUInt32BE(16),256);assert.equal(bytes.readUInt32BE(20),256);
 const entry=source.rows.find(s=>s.reading===item.reading);
 assert.equal(entry.word,item.word);assert.equal(entry.entryId,item.entryId);assert.deepEqual(entry.senseIndexes,item.senseIndexes);
}
for(const [reading,word] of [['うえ','上'],['いっとう','一等'],['かいちょう','快調'],['かんじょう','感情'],['げんそく','減速'],['じどう','自動'],['けいかい','軽快'],['せいとう','正当']])assert.equal(review.find(r=>r.reading===reading).word,word,'Correct homonym sense');
assert.deepEqual(review.find(r=>r.reading==='やすむ').senseIndexes,[1]);
assert.equal(plan.newImages.length,summary.generatedImages);assert.equal(summary.missingImages,0);
console.log(JSON.stringify({passed:true,newWords:512,images:512,preservedOriginalRows:summary.baselineRows,homonymSenses:true,blacklist:true}));
