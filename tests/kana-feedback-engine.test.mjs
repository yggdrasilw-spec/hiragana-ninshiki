import assert from 'node:assert/strict';
import {evaluate,match,box,resample} from '../kana-feedback-engine.mjs';
const stroke=points=>({points:points.map(([x,y])=>({x,y}))});
const ref=[stroke([[80,20],[75,80],[70,140],[80,190],[110,210],[150,200],[180,170]])];
const check=strokes=>evaluate({char:'し',strokes,reference:ref});
assert.equal(check(ref).identity.status,'unavailable');assert.equal(check(ref).beauty.length,0);assert.equal(check(ref).writing.length,0);
const translated=ref.map(s=>({...s,points:s.points.map(p=>({x:p.x*2+140,y:p.y*2-20}))}));
assert.ok(match(translated,ref).available);assert.equal(check(translated).beauty.length,0);
const reversed=ref.map(s=>({...s,points:[...s.points].reverse()}));
assert.ok(check(reversed).writing.some(r=>r.id.startsWith('direction')));assert.equal(check(reversed).identity.status,'unavailable');
const wide=ref.map(s=>({...s,points:s.points.map(p=>({x:p.x*1.5,y:p.y*.8}))}));
assert.ok(check(wide).beauty.some(r=>r.id==='outline'));
const two=[stroke([[30,40],[180,40]]),stroke([[30,160],[180,160]])];
const swapped=evaluate({char:'こ',strokes:[two[1],two[0]],reference:two});
assert.equal(swapped.writing.filter(r=>r.id.startsWith('order')).length,2);
const missing=evaluate({char:'こ',strokes:[two[0]],reference:two});assert.equal(missing.mapping.available,false);assert.equal(missing.beauty.length,0);
const unequal=evaluate({char:'こ',strokes:[stroke([[30,40],[140,40]]),two[1]],reference:two});
assert.ok(unequal.beauty.some(r=>r.id==='length-0'));
const rounded=[stroke([...Array.from({length:12},(_,i)=>[30,10+i*10]),...Array.from({length:25},(_,i)=>[90-60*Math.cos(i/24*Math.PI/2),120+60*Math.sin(i/24*Math.PI/2)]),[150,180],[190,180]])];
const angular=evaluate({char:'し',strokes:[stroke([[30,10],[30,180],[190,180]])],reference:rounded});
assert.ok(angular.beauty.some(r=>r.id==='curve-0'));
const dot=check([stroke([[10,10]])]);assert.equal(dot.mapping.available,false);assert.equal(dot.beauty.length,0);
const bad=check([{points:[{x:NaN,y:10}]}]);assert.equal(bad.mapping.available,false);
const unsupported=evaluate({char:'ア',strokes:ref,reference:ref});assert.equal(unsupported.identity.status,'unavailable');assert.equal(unsupported.beauty.length,0);
const scribble=check([stroke([[0,0],[280,0],[0,280],[280,280],[0,0]])]);assert.equal(scribble.mapping.available,false);assert.equal(scribble.beauty.length,0);
assert.deepEqual(box([]),null);assert.equal(resample([{x:0,y:0},{x:10,y:0}],5)[2].x,5);
assert.equal(match([],[]).available,false);
for(const outcome of [check(ref),check(wide),check(reversed),missing,dot,bad,scribble,unsupported])assert.notEqual(outcome.identity.status,'pass');
console.log('Kana comparison: invariance, reversed direction, stroke order, aspect, rejection and no automatic pass passed.');
