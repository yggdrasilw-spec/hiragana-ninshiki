const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path');
const assets = require('../shiritori-assets.js');
const root = path.resolve(__dirname, '..');
(async () => {
  for (const invalid of ['', '../secret.png', 'assets/shiritori/../secret.png', 'https://evil.example/image.png', 'assets/shiritori/sheets/source.png', 'assets/shiritori/%2e%2e.png', 'assets/shiritori/a.png?url=evil']) assert.equal(assets.url(invalid), null, invalid);
  assert.equal(assets.url('./assets/shiritori/hakushu.png'), assets.origin + '/assets/shiritori/hakushu.png');
  assert.equal(assets.url('shiritori_title.png'), assets.origin + '/shiritori_title.png');
  const rows = fs.readFileSync(path.join(root, 'whitelist.csv'), 'utf8').trim().split(/\r?\n/).slice(1).map(l => l.split(','));
  const keys = [...new Set(rows.map(r => r[6]).filter(Boolean))];
  assert(keys.every(key => assets.url(key)), 'Every dictionary image uses the trusted origin');
  const { default: worker } = await import('../cloudflare/images/worker.mjs');
  let reads = 0;
  const object = { body: 'image-bytes', size: 11, httpEtag: '"test-etag"', customMetadata: { sha256: 'a'.repeat(64) }, writeHttpMetadata(headers) { headers.set('Content-Type', 'image/png'); } };
  const env = { ASSETS: { async get(key, options) { reads++; if (key.endsWith('missing.png')) return null; if (options?.onlyIf?.etagDoesNotMatch === object.httpEtag) { const { body, ...metadata } = object; return metadata; } return object; }, async head() { reads++; return object; } } };
  const call = (key, options) => worker.fetch(new Request(assets.origin + '/' + key, options), env);
  let response = await call('assets/shiritori/hakushu.png');
  assert.equal(response.status, 200); assert.equal(await response.text(), 'image-bytes');
  assert.equal(response.headers.get('Access-Control-Allow-Origin'), '*');
  assert.equal(response.headers.get('Content-Type'), 'image/png');
  assert.equal(response.headers.get('ETag'), '"test-etag"');
  response = await call('assets/shiritori/hakushu.png', { headers: { 'If-None-Match': '"test-etag"' } });
  assert.equal(response.status, 304); assert.equal(await response.text(), '');
  response = await call('assets/shiritori/hakushu.png', { method: 'HEAD' });
  assert.equal(await response.text(), ''); assert.equal(response.headers.get('Content-Length'), '11');
  response = await call('assets/shiritori/hakushu.png', { method: 'HEAD', headers: { 'If-None-Match': '"test-etag"' } });
  assert.equal(response.status, 304);
  response = await call('assets/shiritori/missing.png'); assert.equal(response.status, 404);
  const before = reads;
  for (const key of ['assets/shiritori/sheets/source.png', 'data/image-coverage/evidence.png', 'archive.png', 'assets/shiritori/%2e%2e%2fsecret.png']) assert.equal((await call(key)).status, 404);
  assert.equal(reads, before, 'Private paths never reach the bucket');
  assert.equal((await call('assets/shiritori/hakushu.png', { method: 'PUT', body: 'overwrite' })).status, 405);
  assert.equal((await call('assets/shiritori/hakushu.png', { method: 'OPTIONS' })).status, 204);
  console.log(JSON.stringify({ passed: true, dictionaryImageKeys: keys.length, checks: ['trusted origin', 'all dictionary references', 'private paths blocked', 'read-only', 'CORS', 'content type', 'HEAD', 'ETag', 'missing image'] }));
})().catch(error => { console.error(error); process.exitCode = 1; });
