"""Compile the complete meaning-specific editorial grade decisions.

Decisions are bound to the exact CSV SHA256. Dictionary edits require rebasing
the decisions, rather than silently applying row numbers to different meanings.
The CSV, asset manifest and dictionary import history are never rewritten here.
"""
import csv
import hashlib
import json
import subprocess
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def expand(spec):
    for token in spec.split():
        bounds = list(map(int, token.split('-')))
        if len(bounds) not in (1, 2) or bounds[0] > bounds[-1]:
            raise ValueError(f'Invalid decision range: {token}')
        yield from range(bounds[0], bounds[-1]+1)


def build(root=ROOT):
    source_bytes = (root / 'whitelist.csv').read_bytes()
    source_hash = hashlib.sha256(source_bytes).hexdigest()
    rows = list(csv.DictReader(source_bytes.decode('utf-8-sig').splitlines()))
    decisions = json.loads((root / 'data/shiritori-grade-decisions.json').read_text(encoding='utf-8'))
    if decisions.get('schema') != 2 or decisions.get('indexBase') != 0:
        raise ValueError('Unsupported grade decision schema')
    if decisions.get('sourceSha256') != source_hash or decisions.get('reviewedRows') != len(rows):
        raise ValueError('Dictionary changed: rebase decisions against exact meanings before rebuilding')
    assignments = {}
    for level in range(1, 6):
        for index in expand(decisions['levels'][str(level)]):
            if index in assignments:
                raise ValueError(f'Duplicate grade decision: row {index}')
            assignments[index] = level
    if set(assignments) != set(range(len(rows))):
        raise ValueError('Every dictionary meaning requires exactly one explicit grade decision')

    policy, review = {}, []
    for index, row in enumerate(rows):
        level = assignments[index]
        key = '\t'.join((row['reading'], row['word'], row['meaning']))
        if key in policy and policy[key] != level:
            raise ValueError(f'Identical meaning has conflicting grades: {row["word"]}')
        policy[key] = level
        review.append(dict(id=index+1, reading=row['reading'], word=row['word'],
                           meaning=row['meaning'], level=level, status='assigned',
                           reason=decisions.get('notes', {}).get(str(index), decisions['criteria'][str(level)])))
    # Omit grade 4 keys in the runtime file: unmatched/new meanings also remain
    # outside the elementary bands. The full ledger explicitly includes grade 4.
    runtime = dict(version=2, sourceSha256=source_hash, reviewedMeanings=len(rows),
                   levels={key: value for key, value in policy.items() if value != 4})
    return runtime, review


def main():
    runtime, review = build()
    (ROOT / 'shiritori-grade-policy.js').write_text(
        '/* Generated by scripts/build-shiritori-grade-bands.py. Exact meanings only. */\n'
        + 'window.ShiritoriGradePolicy='
        + json.dumps(runtime, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
    (ROOT / 'data/shiritori-grade-review.json').write_text(
        json.dumps(review, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    subprocess.run(['node', str(ROOT / 'scripts/build-shiritori-delivery.cjs')], cwd=ROOT, check=True)
    print(json.dumps(dict(Counter(row['level'] for row in review))))


if __name__ == '__main__':
    main()
