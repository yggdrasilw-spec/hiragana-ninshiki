/* Bind researched source links to exact reading + spelling + meaning keys. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
function build(){
  const dir=path.join(root,'data/meaning-review'),entries={},excluded=[];
  for(const file of fs.readdirSync(dir).filter(f=>/^source-check-.*-batch.*\.json$/.test(f)).sort()){
    const batch=JSON.parse(fs.readFileSync(path.join(dir,file),'utf8'));
    for(const r of [...(batch.changes||[]),...(batch.additions||[]),...(batch.retained||[])]){
      if(r.status!=='source-checked'||r.withdrawn)continue;
      assert.equal(r.sources.length,r.sourceTitles.length);
      assert.ok(r.sources.length&&r.sources.every(url=>/^https:\/\//.test(url)));
      const key=[r.reading,r.word,r.meaning].join('\t');
      entries[key]={title:r.sourceTitles[0],url:r.sources[0],checkedAt:r.checkedAt,
        ...(r.sources.length>1?{references:r.sources.slice(1).map((url,i)=>({url,title:r.sourceTitles[i+1]}))}:{})};
    }
    for(const record of batch.exclusions||[]){
      assert.equal(record.baselineKey.length,3);
      assert.ok(record.reason);
      excluded.push(record.baselineKey.join('\t'));
    }
  }
  return '/* Generated by scripts/build-shiritori-meaning-sources.cjs. Exact meanings only. */\n'+
    '(function(root){const entries='+JSON.stringify(entries)+',excluded=new Set('+JSON.stringify(excluded)+');'+
    'const key=(reading,word,meaning)=>[reading,word,meaning].join("\\t");'+
    'root.ShiritoriMeaningSources={get:(...sense)=>entries[key(...sense)]||null,isExcluded:(...sense)=>excluded.has(key(...sense))};'+
    '})(typeof window==="undefined"?globalThis:window);\n';
}
const output=build(),dest=path.join(root,'shiritori-meaning-sources.js');
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(dest,'utf8'),output,'Meaning sources need rebuilding');
else fs.writeFileSync(dest,output);
console.log(JSON.stringify({checked:process.argv.includes('--check'),bytes:Buffer.byteLength(output)}));
